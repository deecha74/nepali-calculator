export function getBankEffectiveRate(bank: CommercialBank, category: LoanCategory): number {
  let premium = bank.homeLoanPremium;
  if (category === "auto") premium = bank.autoLoanPremium;
  if (category === "ev") premium = bank.evLoanPremium;
  if (category === "education") premium = bank.educationLoanPremium;
  if (category === "personal") premium = bank.personalLoanPremium;
  return Number((bank.baseRate + premium).toFixed(2));
}

export function calculateMonthlyEmi(principal: number, annualRate: number, tenureYears: number): number {
  if (principal <= 0 || annualRate <= 0 || tenureYears <= 0) return 0;
  const monthlyRate = annualRate / 12 / 100;
  const totalMonths = tenureYears * 12;
  const factor = Math.pow(1 + monthlyRate, totalMonths);
  return Math.round((principal * monthlyRate * factor) / (factor - 1));
}

